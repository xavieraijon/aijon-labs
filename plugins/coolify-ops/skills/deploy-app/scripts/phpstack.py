def read(path: Path) -> str:
    try:
        if path.stat().st_size > MAX_FILE:
            return ""
        return path.read_text(errors="ignore")
    except (OSError, UnicodeDecodeError):
        return ""


def load_json(path: Path) -> dict:
    try:
        data = json.loads(read(path) or "{}")
    except json.JSONDecodeError:
        return {}
    return data if isinstance(data, dict) else {}


def strip_php_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"(?m)^\s*(?://|#).*$|\s//[^\n'\"]*$", "", text)


def php_framework(root: Path) -> str | None:
    """«laravel», «symfony» or None, from composer.json require."""
    require = load_json(root / "composer.json").get("require") or {}
    if "laravel/framework" in require:
        return "laravel"
    if "symfony/framework-bundle" in require:
        return "symfony"
    return None


def locked_packages(root: Path) -> list[dict]:
    packages = load_json(root / "composer.lock").get("packages") or []  # not packages-dev: installed with --no-dev
    return [p for p in packages if isinstance(p, dict)]


def laravel_major(root: Path, require: dict) -> int | None:
    for p in locked_packages(root):
        if p.get("name") == "laravel/framework":
            m = re.search(r"(\d+)", str(p.get("version", "")))
            if m:
                return int(m.group(1))
    m = re.search(r"(\d+)", str(require.get("laravel/framework", "")))
    return int(m.group(1)) if m else None


def php_version(composer: dict) -> str:
    """PHP minor for the image: config.platform.php, a capped constraint, or max(lower bound, 8.4)."""
    platform = str(((composer.get("config") or {}).get("platform") or {}).get("php") or "")
    m = re.match(r"\s*(\d+)\.(\d+)", platform)
    if m:
        return f"{m.group(1)}.{m.group(2)}"
    spec = str((composer.get("require") or {}).get("php") or "")
    if "|" not in spec:
        m = re.fullmatch(r"\s*(?:~\s*(\d+)\.(\d+)\.\d+|(\d+)\.(\d+)\.[*x])\s*", spec)
        if m:
            major_, minor = (m.group(1), m.group(2)) if m.group(1) else (m.group(3), m.group(4))
            return f"{major_}.{minor}"
        m = re.search(r"<\s*(\d+)\.(\d+)", spec)
        if m and int(m.group(2)) > 0:
            return f"{m.group(1)}.{int(m.group(2)) - 1}"
    m = re.search(r"(\d+)\.(\d+)", spec)
    if not m or int(m.group(1)) != 8:
        return "8.4"
    return f"8.{max(int(m.group(2)), 4)}"


def php_extensions(root: Path, composer: dict, php: str) -> tuple[list[str], list[str]]:
    """Extensions to install (beyond the image's) and the names skipped because they are not plain names."""
    wanted: set[str] = set()
    for require in [composer.get("require") or {}] + [p.get("require") or {} for p in locked_packages(root)]:
        wanted |= {k[4:].lower() for k in require if isinstance(k, str) and k.lower().startswith("ext-")}
    wanted = {"opcache" if x == "zend-opcache" else x for x in wanted}
    skipped = sorted(x for x in wanted if not EXTENSION.fullmatch(x))
    exts = {x for x in wanted if EXTENSION.fullmatch(x)} - BUILTIN_EXTENSIONS - MYSQL_EXTENSIONS - {"opcache"}
    exts.add("pdo_pgsql")
    if tuple(int(x) for x in php.split(".")) < (8, 5):  # built in from PHP 8.5
        exts.add("opcache")
    return sorted(exts), skipped


def composer_repositories(root: Path, composer: dict) -> tuple[str | None, str]:
    """(blocking reason or None, COMPOSER_COPY key)."""
    repos = composer.get("repositories") or []
    if isinstance(repos, dict):
        repos = list(repos.values())
    copy = "manifests"
    if (root / "auth.json").exists():
        return ("auth.json found: private Composer repositories need credentials the build does not have "
                "(and auth.json must not be committed): add your own Dockerfile", copy)
    for repo in repos:
        if not isinstance(repo, dict):
            continue
        kind, url = str(repo.get("type", "")), str(repo.get("url", ""))
        host = urlparse(url).hostname or re.sub(r"^[^@]*@", "", url).split(":")[0] or kind  # never user:token@
        if kind == "composer" and not re.search(r"(^|//)(repo\.)?packagist\.org", url):
            return (f"private Composer repository ({host}): the build has no credentials for it: add your own "
                    "Dockerfile", copy)
        if kind in ("vcs", "git", "github", "gitlab", "bitbucket") and not any(h in url for h in PUBLIC_VCS_HOSTS):
            return f"Composer repository on a private host ({host}): add your own Dockerfile", copy
        if kind in ("path", "artifact"):
            target = (root / url.split("*")[0]).resolve()
            if not target.is_relative_to(root.resolve()):
                return (f"Composer {kind} repository outside the project ({url}): the build only sees this folder: "
                        "add your own Dockerfile", copy)
            copy = "all"
    return None, copy


def env_example(root: Path) -> dict[str, str]:
    """.env.example key → value (kept inside this module: values never reach the JSON output)."""
    out = {}
    for line in read(root / ".env.example").splitlines():
        m = re.match(r"\s*([A-Z_][A-Z0-9_]*)\s*=\s*(.*)", line)
        if m:
            out[m.group(1)] = m.group(2).split(" #")[0].strip().strip("\"'")
    return out


def node_version(pkg: dict, root: Path) -> str:
    pinned = (read(root / ".nvmrc") or read(root / ".node-version")).strip()
    m = re.search(r"(\d+)", pinned)
    if m:
        return m.group(1)
    m = re.search(r"(\d+)", str((pkg.get("engines") or {}).get("node") or ""))
    return str(max(int(m.group(1)), 22)) if m else "22"  # engines is a lower bound; Vite 7+ needs Node 20.19+


def text_of(root: Path, files: list[Path], prefix: str, suffix: str = ".php") -> str:
    return "\n".join(read(f) for f in files
                     if str(f.relative_to(root)).startswith(prefix) and f.name.endswith(suffix))


def analyze_laravel(root: Path, files: list[Path]) -> dict:
    composer = load_json(root / "composer.json")
    require = composer.get("require") or {}
    pkg = load_json(root / "package.json")
    scripts = pkg.get("scripts") or {}
    bootstrap = read(root / "bootstrap" / "app.php")
    views = "\n".join(read(f) for f in files if str(f.relative_to(root)).startswith("resources/views/"))
    app_code = text_of(root, files, "app/")
    example = env_example(root)
    r: dict = {"language": "php", "framework": "laravel", "port": 8080, "migrations": True}
    blockers: list[str] = []

    # --- version and structure
    version = laravel_major(root, require)
    r["laravel_version"] = version
    if version is not None and version < 11:
        blockers.append(f"Laravel {version} (10 or older) is not supported: upgrade to 11+, or add your own Dockerfile")
    elif "Application::configure" not in bootstrap or (root / "app" / "Http" / "Kernel.php").exists():
        blockers.append("Laravel 11+ with the pre-11 application structure (app/Http/Kernel.php) is not supported: "
                        "add your own Dockerfile")
    if not (root / "artisan").exists() or not (root / "public" / "index.php").exists():
        blockers.append("artisan or public/index.php is not at the repository root: add your own Dockerfile")
    reason, r["composer_copy"] = composer_repositories(root, composer)
    if reason:
        blockers.append(reason)

    # --- PHP
    r["php_version"] = php_version(composer)
    exts, skipped = php_extensions(root, composer, r["php_version"])
    r["php_extensions"] = " ".join(exts)
    if skipped:
        r["warning_extensions"] = f"PHP extensions not installed (unusual names): {', '.join(skipped)}"
    if not (root / "composer.lock").exists():
        r["warning_lock"] = "no composer.lock: dependencies are resolved at build time (builds are not reproducible)"

    # --- front end
    r["frontend"] = bool(scripts.get("build"))
    if r["frontend"]:
        r["node_version"] = node_version(pkg, root)
        r["verify_expect"] = "https://{domain}/build/"
        if not (root / "package-lock.json").exists() and any((root / f).exists() for f in ("pnpm-lock.yaml", "yarn.lock")):
            r["warning_package_manager"] = "the front end is installed with npm (pnpm/yarn lock files are ignored)"
    r["template"] = "php-laravel" if r["frontend"] else "php-laravel-api"
    unguarded = [f for f in files if str(f.relative_to(root)).startswith("resources/views/")
                 and "@vite(" in (t := read(f)) and "manifest.json" not in t]
    if unguarded and not r["frontend"]:
        blockers.append("the views load Vite assets (@vite) but package.json has no build script: add one, or add "
                        "your own Dockerfile")
    vite_config = "".join(read(root / n) for n in ("vite.config.js", "vite.config.ts", "vite.config.mjs"))
    if "buildDirectory" in vite_config:
        blockers.append("vite.config sets buildDirectory: the template serves public/build only (remove it, or add "
                        "your own Dockerfile)")
    if re.search(r"\{\{\s*mix\(", views) or "laravel-mix" in json.dumps(pkg):
        blockers.append("Laravel Mix is not supported (the template builds with Vite): migrate to Vite, or add your "
                        "own Dockerfile")

    # --- routes and checks
    m = re.search(r"health:\s*['\"]([^'\"]+)['\"]", strip_php_comments(bootstrap))
    r["check_routes"] = [m.group(1)] if m and HEALTH_PATH.fullmatch(m.group(1)) else []
    r["local_env"] = [f"APP_KEY={LOCAL_APP_KEY}", "DB_CONNECTION=sqlite", "DB_DATABASE=/tmp/local-check.sqlite",
                      "SESSION_SECURE_COOKIE=false", "APP_URL=http://localhost"]
    r["generated_env"] = ["APP_KEY:laravel"]
    r["url_env"] = ["APP_URL"]
    r["db_env_key"] = "DB_URL"
    r["managed_env"] = list(MANAGED_ENV)

    # --- trusted proxies
    own = read(root / "config" / "trustedproxy.php")
    if own and GENERATED_MARKER not in own:
        r["trust_proxies"] = "project"
    elif not own and "trustProxies(" in strip_php_comments(bootstrap):
        r["trust_proxies"] = "project"
    else:
        r["trust_proxies"] = "generated"
    if r["trust_proxies"] == "project":
        r["warning_proxies"] = ("the project decides which proxies to trust: it must trust Coolify's proxy (e.g. "
                                "trustProxies(at: '*')) or URLs and assets will use http://")

    # --- databases (set here alone: the generic checks of analyze.py do not apply to Laravel)
    dbs = ["postgresql"]
    database_php = read(root / "config" / "database.php")
    if database_php:
        pg = re.search(r"['\"]pgsql['\"]\s*=>\s*\[(.*?)\n\s*\],", database_php, re.S)
        if not pg or "DB_URL" not in pg.group(1):
            blockers.append("config/database.php has no pgsql connection that reads DB_URL: add 'url' => "
                            "env('DB_URL') to the pgsql connection")
    redis_code = re.search(r"\bRedis::|Facades\\Redis\b", app_code)
    if any(p in require for p in ("predis/predis", "ext-redis", "laravel/horizon")) or redis_code:
        dbs.append("redis")
    elif any(example.get(k) == "redis" for k in ("CACHE_STORE", "SESSION_DRIVER", "QUEUE_CONNECTION")):
        r["warning_redis"] = ".env.example uses Redis for cache, sessions or queue: deployed with the database drivers"
    if "mongodb/laravel-mongodb" in require:
        dbs.append("mongodb")
    if example.get("DB_CONNECTION") in ("mysql", "mariadb"):
        r["warning_mysql"] = f".env.example uses {example['DB_CONNECTION']}: the app will use PostgreSQL"
    r["databases"] = dbs

    # --- login and things that are not deployed
    r["has_login"] = (any(p in require for p in LOGIN_PACKAGES) or (root / "routes" / "auth.php").exists()
                      or bool(re.search(r"\bAuth::(attempt|login|routes)\b", app_code)))
    if (root / "app" / "Jobs").is_dir() or "ShouldQueue" in app_code:
        r["warning_queue"] = ("queued jobs are not processed: no queue worker is deployed (QUEUE_CONNECTION=sync "
                              "runs them inline)")
    console = read(root / "routes" / "console.php")
    if "Schedule::" in console or "->withSchedule(" in bootstrap:
        r["warning_schedule"] = "scheduled tasks do not run: no scheduler is deployed"
    extra = [p for p in ("laravel/reverb", "laravel/octane") if p in require]
    if extra:
        r["warning_services"] = f"{', '.join(extra)}: only the web app is deployed (no extra process)"
    if scripts.get("build:ssr"):
        r["warning_ssr"] = "Inertia SSR is not deployed: pages are rendered in the browser"
    if example.get("FILESYSTEM_DISK") == "public" or "storage/app/public" in app_code or "disk('public')" in app_code:
        r["warning_uploads"] = "files stored on the public disk are lost on every deploy (no persistent storage)"

    if blockers:
        r.update(template=None, warning_framework="; ".join(blockers))
    return r


def laravel_env(root: Path, files: list[Path], env_vars: dict, own_dockerfile: bool, version: int | None) -> list[str]:
    """Keep only the variables worth asking for (in place) and return warnings."""
    example = env_example(root)
    exclude = SET_BY_SKILL if own_dockerfile else SET_BY_DEPLOYMENT
    in_code: set[str] = set()
    for f in files:
        rel = str(f.relative_to(root))
        if f.suffix == ".php" and not rel.startswith("config/"):
            in_code |= set(re.findall(r"\benv\(\s*['\"]([A-Z_][A-Z0-9_]*)", read(f)))
        elif rel.startswith("resources/") and f.suffix in {".js", ".ts", ".jsx", ".tsx", ".vue", ".svelte"}:
            in_code |= set(re.findall(r"(?:import\.meta\.env|process\.env)\.([A-Z_][A-Z0-9_]*)", read(f)))
    added = {k for k in example if k not in SKELETON_ENV}
    changed = sorted(k for k, v in example.items()
                     if k in SKELETON_ENV and v not in SKELETON_ENV[k] and k not in exclude)
    env_vars["in_code"] = sorted((in_code - set(SKELETON_ENV) | added) - exclude)
    env_vars["example"] = {k: bool(example[k]) for k in sorted(added - exclude)}
    env_vars["changed_defaults"] = changed
    warnings = []
    if changed:
        warnings.append(".env.example sets its own value for " + ", ".join(changed) + ": give them a value with "
                        "env-push, or the defaults of config/*.php apply")
    if version and version > NEWEST_SKELETON:
        warnings.append(f"Laravel {version} is newer than the skeleton table: some variables asked may be new "
                        "skeleton defaults")
    return warnings
